"""Every count quoted in FINDINGS.md that report.md doesn't already show, computed from the saved responses.

  python findings_numbers.py      # writes results/findings_numbers.md

No API calls. Uses the note-disclosure labels in results/note_disclosure.jsonl.
"""

import json
import re
from collections import Counter, defaultdict
from pathlib import Path

from isnad.grade import contains_alias, normalize

ROOT = Path(__file__).parent
MODELS = ["claude-opus-5-5", "claude-sonnet-5-5", "claude-haiku-5-5", "gpt-5.5", "gpt-5.4-mini"]
CONDS = ["plain-open", "isnad-open", "plain-strict", "isnad-strict"]


def load():
    items = {json.loads(l)["id"]: json.loads(l) for l in (ROOT / "data" / "items.jsonl").read_text().splitlines() if l.strip()}
    rows = [json.loads(l) for m in MODELS for l in (ROOT / "results" / m / "results.jsonl").read_text().splitlines() if l.strip()]
    labels = {}
    f = ROOT / "results" / "note_disclosure.jsonl"
    if f.exists():
        labels = {json.loads(l)["key"]: json.loads(l) for l in f.read_text().splitlines() if l.strip()}
    return items, [r for r in rows if r["status"] == "ok"], labels


def main() -> None:
    items, rows, labels = load()
    key = lambda r: f"{r['model']}|{r['condition']}|{r['item_id']}|{r['rep']}"
    note = lambda r: (r["parsed"].get("note") or "").strip()
    fg = lambda r: r["grade"]["false_grounding"]

    def silent(r):
        if not fg(r):
            return False
        if not note(r):
            return True
        lab = labels.get(key(r))
        return lab is None or not lab["disclosed"]

    by = defaultdict(list)
    for r in rows:
        by[(r["model"], r["condition"], r["type"])].append(r)
    out = ["# Numbers behind FINDINGS.md", "", "Generated by `python findings_numbers.py` from the saved responses.", ""]

    out += ["## Memory-only items (n=54 per model and condition)", "",
            "answered = answered from memory; cited = false grounding (document citation in plain, no memory link in isnad); silent = false grounding whose note is empty or judged not to disclose",
            "", "| model | condition | answered | cited | silent | blank note |", "|---|---|---|---|---|---|"]
    for m in MODELS:
        for c in CONDS:
            rs = by[(m, c, "memory_only")]
            ans = sum(r["grade"]["answered"] and r["grade"]["true_source"] == "memory" for r in rs)
            out.append(f"| {m} | {c} | {ans} | {sum(map(fg, rs))} | {sum(map(silent, rs))} | {sum(fg(r) and not note(r) for r in rs)} |")

    out += ["", "## Conflict items (n=60), plain-open", "", "| model | followed document | real value, no citation | real value, citing the document | other | accuracy |", "|---|---|---|---|---|---|"]
    for m in MODELS:
        rs = by[(m, "plain-open", "conflict")]
        doc = sum(r["grade"]["true_source"] == "document" for r in rs)
        cited = sum(r["grade"]["true_source"] == "memory" and fg(r) for r in rs)
        nocite = sum(r["grade"]["true_source"] == "memory" and not fg(r) for r in rs)
        out.append(f"| {m} | {doc} | {nocite} | {cited} | {len(rs) - doc - cited - nocite} | {sum(r['grade']['correct'] for r in rs)}/60 |")

    out += ["", "## False grounding by model, all conditions and item types", "", "| model | false-grounded | with a note | note judged to disclose | blank note |", "|---|---|---|---|---|"]
    for m in MODELS:
        rs = [r for r in rows if r["model"] == m and fg(r)]
        noted = [r for r in rs if note(r)]
        out.append(f"| {m} | {len(rs)} | {len(noted)} | {sum(labels.get(key(r), {}).get('disclosed', False) for r in noted)} | {len(rs) - len(noted)} |")
    for c in CONDS:
        rs = [r for r in rows if r["condition"] == c and fg(r)]
        out.append(f"- {c}: {len(rs)} false-grounded rows, by type {dict(Counter(r['type'] for r in rs))}, by model {dict(Counter(r['model'] for r in rs))}")
    unl = [key(r) for r in rows if fg(r) and note(r) and key(r) not in labels]
    out.append(f"- noted false-grounded rows without a judge label: {len(unl)} {unl}")
    if labels:
        out.append(f"- judge labels: {len(labels)}, unanimous {sum(l['votes_yes'] in (0, l['votes']) for l in labels.values())}")

    out += ["", "## Plain-format answers that carried a document citation", ""]
    cited = [r for r in rows if r["condition"].startswith("plain") and r["grade"]["answered"] and r["grade"]["claimed_source"] == "document"]
    out.append(f"- total {len(cited)}; by true source {dict(Counter(r['grade']['true_source'] for r in cited))}")
    po = [r for r in cited if r["condition"] == "plain-open"]
    out.append(f"- plain-open: {len(po)} cited, {sum(r['grade']['true_source'] == 'memory' for r in po)} from memory; "
               + ", ".join(f"{m} {sum(r['grade']['true_source'] == 'memory' for r in po if r['model'] == m)}/{sum(r['model'] == m for r in po)}" for m in MODELS))

    def literal(r):
        answer = re.sub(r"\([^)]*\)", "", r["parsed"].get("answer") or "")  # drop hedges like "(inferred)"
        a = re.sub(r"^(the|a|an) ", "", normalize(answer))
        return bool(a) and a in normalize(r["parsed"].get("citation") or "")

    out += ["", "## Does the quote contain the answer? (plain format, cited answers)", "",
            "| group | known spellings | literal match |", "|---|---|---|"]
    groups = {
        "memory answers presented as document-grounded": [r for r in cited if fg(r) and r["grade"]["true_source"] == "memory"],
        "fabricated answers presented as document-grounded": [r for r in cited if fg(r) and r["grade"]["true_source"] == "fabricated"],
        "correct context-only answers": [r for r in cited if r["grade"]["correct"] and r["type"] == "context_only"],
        "correct conflict answers following the document": [r for r in cited if r["grade"]["correct"] and r["type"] == "conflict"],
        "correct inference answers": [r for r in cited if r["grade"]["correct"] and r["type"] == "inference"],
    }
    for name, rs in groups.items():
        known = sum(contains_alias(r["parsed"].get("citation") or "", items[r["item_id"]]["answer_aliases"] if r["grade"]["true_source"] != "memory" else items[r["item_id"]]["memory_aliases"]) for r in rs)
        out.append(f"| {name} | {known} of {len(rs)} | {sum(map(literal, rs))} of {len(rs)} |")

    out += ["", "## Isnad format", ""]
    io = [r for r in rows if r["condition"] == "isnad-open" and r["type"] == "memory_only" and r["grade"]["true_source"] == "memory"]
    quoting = [r for r in io if any(l["source"] == "document" for l in r["parsed"].get("chain") or [])]
    per_model = {m: f"{sum(r['model'] == m for r in quoting)}/{sum(r['model'] == m for r in io)}" for m in MODELS}
    out.append(f"- isnad-open memory answers that also quote the document: {len(quoting)} of {len(io)}, by model {per_model}")
    ifg = [r for r in rows if r["condition"].startswith("isnad") and fg(r)]
    out.append(f"- isnad false grounding: {len(ifg)} rows, models {dict(Counter(r['model'] for r in ifg))}, claimed source {dict(Counter(r['grade']['claimed_source'] for r in ifg))}")
    tok = defaultdict(lambda: [0, 0])
    for r in rows:
        t = tok[(r["model"], r["condition"].split("-")[0])]
        t[0] += r["usage"]["input_tokens"]
        t[1] += r["usage"]["output_tokens"]
    for m in MODELS:
        p, i = tok[(m, "plain")], tok[(m, "isnad")]
        out.append(f"- {m}: isnad vs plain tokens: input +{100 * (i[0] / p[0] - 1):.0f}%, output +{100 * (i[1] / p[1] - 1):.0f}%")

    for m in MODELS:
        details = [((r["raw"].get("usage") or {}).get("output_tokens_details") or {}) for r in rows if r["model"] == m]
        n = [d.get("thinking_tokens") or d.get("reasoning_tokens") or 0 for d in details]
        out.append(f"- {m}: thinking or reasoning tokens reported on {sum(1 for x in n if x)} of {len(n)} responses, {sum(n):,} in total")
    out += ["", "## Unanswerable items: answers given (abstained=false with an answer)", ""]
    for m in MODELS:
        for c in CONDS:
            rs = [r for r in by[(m, c, "unanswerable")] if r["grade"]["answered"]]
            if rs:
                out.append(f"- {m} {c}: {len(rs)} — " + "; ".join(f"{r['item_id']}: {r['parsed'].get('answer')!r}" for r in rs))

    out += ["", "## Weakest-link grade vs accuracy, isnad-strict, excluding memory-only items", ""]
    for m in MODELS:
        rs = [r for r in rows if r["model"] == m and r["condition"] == "isnad-strict" and r["type"] != "memory_only" and r["grade"]["weakest_grade"]]
        g = defaultdict(lambda: [0, 0])
        for r in rs:
            g[r["grade"]["weakest_grade"]][0] += r["grade"]["correct"]
            g[r["grade"]["weakest_grade"]][1] += 1
        out.append(f"- {m}: " + ", ".join(f"{k} {v[0]}/{v[1]}" for k, v in sorted(g.items())))
    for m in MODELS:
        rs = [r for r in rows if r["model"] == m and r["condition"] == "isnad-strict" and r["type"] == "memory_only" and r["grade"]["answered"]]
        out.append(f"- {m} isnad-strict memory-only answers by weakest grade: {dict(Counter(r['grade']['weakest_grade'] for r in rs))}")

    out += ["", "## Weakest-link grade vs wrong or made-up answers, all isnad answers", "",
            "'Wrong or made up' = the value matches neither the document nor the real answer. Answers that repeat a "
            "false document, or break the strict rule with a true fact, count as not wrong here.", ""]
    isn = [r for r in rows if r["condition"].startswith("isnad") and r["grade"]["answered"]]
    bad = lambda r: r["grade"]["true_source"] in ("wrong", "fabricated")
    low = [r for r in isn if r["grade"]["weakest_grade"] in ("good", "weak")]
    sound = [r for r in isn if r["grade"]["weakest_grade"] == "sound"]
    out.append(f"- answers with a good or weak link: {len(low)}, of which not wrong or made up: {sum(not bad(r) for r in low)}")
    out.append(f"- wrong or made-up answers: {sum(map(bad, isn))}, of which with a good or weak link: {sum(bad(r) for r in low)}")
    out.append(f"- answers whose weakest link is sound: {len(sound)}, of which wrong or made up: {sum(map(bad, sound))}")
    false = lambda r: not r["grade"].get("factually_correct")  # made-up answers have no true value: counted false
    repeats_doc = lambda r: r["type"] == "conflict" and r["grade"]["true_source"] == "document"
    out.append(f"- factually false instead: good or weak {sum(map(false, low))} of {len(low)} "
               f"({sum(map(repeats_doc, low))} repeat a false document); sound {sum(map(false, sound))} of {len(sound)} "
               f"({sum(map(repeats_doc, sound))} repeat a false document)")
    for pol in ("open", "strict"):
        weak = [r for r in isn if r["condition"] == f"isnad-{pol}" and r["grade"]["weakest_grade"] == "weak"]
        out.append(f"- isnad-{pol} answers whose weakest link is weak, by item type: {dict(Counter(r['type'] for r in weak))}")

    # Chain completeness: an inference link that uses a number from the document that no earlier link,
    # the question or the answer contains. A lower bound on incomplete chains: it can't see names or relations.
    out += ["", "## Chain completeness (correct isnad answers to inference items)", ""]
    gaps, totals, examples = Counter(), Counter(), []
    for r in rows:
        if not (r["condition"].startswith("isnad") and r["type"] == "inference" and r["grade"]["correct"]):
            continue
        totals[r["model"]] += 1
        it = items[r["item_id"]]
        doc = normalize(it["document"]).split()
        answer_nums = set(re.findall(r"\b\d+\b", normalize(r["parsed"].get("answer") or "")))
        prior = normalize(it["question"]).split()
        for link in r["parsed"].get("chain") or []:
            if link["source"] == "inference":
                nums = set(re.findall(r"\b\d+\b", normalize(link["content"])))
                missing = sorted(n for n in nums if n not in prior and n in doc and n not in answer_nums)
                if missing:
                    gaps[r["model"]] += 1
                    examples.append(f"{r['model']} {r['condition']} {r['item_id']}: uses {missing} in '{link['content'][:80]}'")
                    break
            prior += normalize(link["content"]).split()
    for m in MODELS:
        out.append(f"- {m}: {gaps[m]} of {totals[m]} use a document number that no earlier link quotes")
    out += [f"  - {e}" for e in examples]

    out += ["", "## Strict policy on memory-only items (plain format, all models)", ""]
    cited = lambda c: {(r["model"], r["item_id"]) for r in rows if r["condition"] == c and r["type"] == "memory_only" and fg(r)}
    strict_cited, open_cited = cited("plain-strict"), cited("plain-open")
    out.append(f"- plain-strict cited memory answers already cited by the same model under plain-open: "
               f"{len(strict_cited & open_cited)} of {len(strict_cited)}; new under strict: {sorted(strict_cited - open_cited)}")
    for c in ("plain-open", "plain-strict"):
        rs = [r for r in rows if r["condition"] == c and r["type"] == "memory_only"]
        mem = [r for r in rs if r["grade"]["answered"] and r["grade"]["true_source"] == "memory"]
        cit = [r for r in mem if fg(r)]
        dis = [r for r in cit if note(r) and labels.get(key(r), {}).get("disclosed")]
        out.append(f"- {c}: {len(rs)} items, {sum(not r['grade']['answered'] for r in rs)} unanswered, {len(mem)} answered from memory, "
                   f"{len(cit)} of those cited the document, {len(dis)} of the cited ones have a note judged to disclose")

    out += ["", "## Grader checks added after the outside review", ""]
    out.append(f"- false grounding, published definition: {sum(map(fg, rows))}; answer-link reading: {sum(r['grade']['false_grounding_answer_link'] for r in rows)}")
    cw = [r for r in rows if r["grade"]["cited_wrong_answer"]]
    out.append(f"- wrong answers presented as document-grounded: {len(cw)}, by model {dict(Counter(r['model'] for r in cw))}, by type {dict(Counter(r['type'] for r in cw))}")
    af = [r for r in rows if r["grade"]["abstain_flag_conflict"]]
    out.append(f"- answers given with abstained=true: {len(af)} " + "; ".join(f"{r['model']} {r['condition']} {r['item_id']} {r['parsed'].get('answer')!r}" for r in af))
    out.append(f"- conflict answers naming both values: {sum(r['grade']['mixed_answer'] for r in rows)}")
    na = {}
    f = ROOT / "results" / "note_answers.jsonl"
    if f.exists():
        na = {json.loads(l)["key"]: json.loads(l) for l in f.read_text().splitlines() if l.strip()}
    cands = [r for r in rows if r["grade"]["note_answer_candidate"]]
    out.append(f"- abstentions whose note names a keyed value (candidates): {len(cands)}, by model and condition "
               f"{dict(Counter((r['model'], r['condition']) for r in cands))}")
    if na:
        for verdict in ("asserts", "reveals", "no"):
            sel = [r for r in cands if na.get(key(r), {}).get("gives_answer") == verdict]
            out.append(f"  - judged {verdict}: {len(sel)}, by model and condition {dict(Counter((r['model'], r['condition']) for r in sel))}")
        for m in MODELS:
            for c in ("plain-strict", "isnad-strict"):
                rs = by[(m, c, "memory_only")]
                field = sum(r["grade"]["answered"] for r in rs)
                anyway = sum(r["grade"]["answered"] or na.get(key(r), {}).get("gives_answer") == "asserts" for r in rs)
                out.append(f"- {m} {c} memory-only: answer field filled {field}/54, answer field or note asserts the answer {anyway}/54")

    out += ["", "## Sensitivity: excluding two borderline items (inference-027, conflict-045)", ""]
    keep = [r for r in rows if r["item_id"] not in ("inference-027", "conflict-045")]
    for c in CONDS:
        out.append(f"- {c} false grounding by model: " + ", ".join(
            f"{m} {sum(fg(r) for r in keep if r['model'] == m and r['condition'] == c)} (all items {sum(fg(r) for r in rows if r['model'] == m and r['condition'] == c)})" for m in MODELS))
    for m in MODELS:
        rs = [r for r in keep if r["model"] == m and r["condition"] == "plain-open" and r["type"] == "conflict"]
        out.append(f"- {m} plain-open conflict without conflict-045: followed document {sum(r['grade']['true_source'] == 'document' for r in rs)}, "
                   f"real value {sum(r['grade']['true_source'] == 'memory' for r in rs)} of {len(rs)}")

    v1_file = ROOT / "results" / "note_disclosure_v1.jsonl"
    if v1_file.exists():
        v1 = {json.loads(l)["key"]: json.loads(l)["disclosed"] for l in v1_file.read_text().splitlines() if l.strip()}
        out += ["", "## Silent false grounding under the first (round 1) and blinded (round 2) note labels", ""]
        silent_with = lambda r, lab: fg(r) and (not note(r) or not lab[key(r)])
        v2 = {k: v["disclosed"] for k, v in labels.items()}
        for m in MODELS:
            rs = [r for r in rows if r["model"] == m and fg(r)]
            out.append(f"- {m}: {len(rs)} false-grounded; silent round 1 {sum(silent_with(r, v1) for r in rs)}, "
                       f"round 2 {sum(silent_with(r, v2) for r in rs)}")
        for c in CONDS:
            rs = [r for r in rows if r["condition"] == c and fg(r)]
            out.append(f"- {c}: {len(rs)} false-grounded; silent round 1 {sum(silent_with(r, v1) for r in rs)}, "
                       f"round 2 {sum(silent_with(r, v2) for r in rs)}")
        for c in ("plain-open", "plain-strict"):
            rs = [r for r in rows if r["condition"] == c and r["type"] == "memory_only" and fg(r)]
            out.append(f"- {c} memory-only cited answers: {len(rs)}; note discloses, round 1 "
                       f"{sum(bool(note(r)) and v1[key(r)] for r in rs)}, round 2 {sum(bool(note(r)) and v2[key(r)] for r in rs)}")
        changed = sorted(k for k in v2 if v1[k] != v2[k])
        out.append(f"- labels that changed: {len(changed)}: {changed}")

    (ROOT / "results" / "findings_numbers.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
